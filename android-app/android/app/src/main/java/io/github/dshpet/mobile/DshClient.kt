package io.github.dshpet.mobile

import android.os.Handler
import android.util.Log
import android.os.Looper
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL
import java.net.URLEncoder
import java.nio.charset.StandardCharsets
import java.util.concurrent.Executors

/**
 * Talks to the dsh-pet host that runs inside a local DSH (`dsh web`).
 *
 * Auth is the DSH launch token: `GET /?token=...` answers with a cookie that
 * the `dsh-pet-7340` routes accept. Everything here blocks, so callers must
 * use a worker thread; [whisperAsync] already does that for the speech loop.
 */
object DshClient {
    private const val CONNECT_TIMEOUT_MS = 6_000
    private const val READ_TIMEOUT_MS = 90_000

    private val io = Executors.newSingleThreadExecutor { r ->
        Thread(r, "dsh-client").apply { isDaemon = true }
    }
    private val main = Handler(Looper.getMainLooper())

    private var cachedBase = ""
    private var cachedToken = ""
    private var cachedCookie = ""

    class DshException(message: String) : Exception(message)

    private fun origin(base: String) = base.trim().trimEnd('/')

    @Synchronized
    private fun cookie(base: String, token: String): String {
        val b = origin(base)
        if (b == cachedBase && token == cachedToken && cachedCookie.isNotEmpty()) return cachedCookie
        val conn = URL("$b/?token=" + URLEncoder.encode(token, "UTF-8")).openConnection() as HttpURLConnection
        conn.instanceFollowRedirects = false
        conn.connectTimeout = CONNECT_TIMEOUT_MS
        conn.readTimeout = CONNECT_TIMEOUT_MS
        conn.requestMethod = "GET"
        val code = conn.responseCode
        val setCookie = conn.headerFields["Set-Cookie"]
            ?.joinToString("; ") { it.substringBefore(";") }.orEmpty()
        conn.errorStream?.close()
        conn.disconnect()
        Log.i("DshClient", "login HTTP $code cookie=" + setCookie.take(24))
        if (setCookie.isBlank()) {
            throw DshException("DSH 登录失败（HTTP $code）；token 可能已失效，重启 DSH 后需要重新粘贴")
        }
        cachedBase = b
        cachedToken = token
        cachedCookie = setCookie
        return setCookie
    }

    private fun call(base: String, token: String, method: String, path: String,
                     body: String?): JSONObject {
        val conn = URL(origin(base) + path).openConnection() as HttpURLConnection
        conn.instanceFollowRedirects = false
        conn.connectTimeout = CONNECT_TIMEOUT_MS
        conn.readTimeout = READ_TIMEOUT_MS
        conn.requestMethod = method
        conn.setRequestProperty("Cookie", cookie(base, token))
        conn.setRequestProperty("Accept", "application/json")
        if (body != null) {
            conn.doOutput = true
            conn.setRequestProperty("Content-Type", "application/json; charset=utf-8")
            conn.outputStream.use { it.write(body.toByteArray(StandardCharsets.UTF_8)) }
        }
        val code = conn.responseCode
        val stream = if (code in 200..299) conn.inputStream else conn.errorStream
        val text = stream?.bufferedReader(StandardCharsets.UTF_8)?.use { it.readText() }.orEmpty()
        conn.disconnect()
        if (text.isBlank()) throw DshException("DSH 返回空响应（HTTP $code）")
        return runCatching { JSONObject(text) }.getOrElse { throw DshException("DSH 响应不是 JSON") }
    }

    private fun petQuery(petId: String) =
        "?pet=" + URLEncoder.encode(petId, "UTF-8") + "&surface=any"

    /** One chat turn; DSH keeps the memory and applies its own persona and model. */
    fun chat(base: String, token: String, petId: String, text: String): ChatReply {
        val json = call(base, token, "POST", "/dsh-pet-7340/chat" + petQuery(petId),
            JSONObject().put("text", text).toString())
        if (!json.optBoolean("ok", false)) {
            throw ChatClient.ChatException(json.optString("message").ifBlank { "DSH 没有回答" })
        }
        Log.i("DshClient", "chat ok len=" + json.optString("text").length)
        return ChatReply(json.optString("text"))
    }

    /** A single self-talk line generated by DSH; null when it could not answer. */
    fun whisper(base: String, token: String, petId: String): String? {
        val json = call(base, token, "POST", "/dsh-pet-7340/whisper" + petQuery(petId), "{}")
        val line = if (json.optBoolean("ok", false)) json.optString("text").takeIf { it.isNotBlank() } else null
        Log.i("DshClient", "whisper ok=" + (line != null) + " text=" + (line ?: ""))
        return line
    }

    fun whisperAsync(base: String, token: String, petId: String, onDone: (String?) -> Unit) {
        io.execute {
            val line = runCatching { whisper(base, token, petId) }.getOrNull()
            main.post { onDone(line) }
        }
    }

    /** Asks DSH to refresh, then reads whatever the balance section currently holds. */
    fun balanceText(base: String, token: String): String {
        runCatching { call(base, token, "POST", "/dsh-pet-7340/balance", "{}") }
        val state = call(base, token, "GET", "/dsh-pet-7340/state", null)
        val section = state.optJSONObject("sections")
            ?.optJSONObject("balance")
            ?.optJSONObject("data")
            ?: throw DshException("DSH 里还没有余额数据")
        // shape: { ok, provider, shape, data: { wallets: [...] } }
        val data = section.optJSONObject("data") ?: section
        val text = pretty(data)
        Log.i("DshClient", "balance=" + text)
        return text
    }

    private fun pretty(data: JSONObject): String {
        data.optString("text").takeIf { it.isNotBlank() }?.let { return it }
        val wallets = data.optJSONArray("wallets")
        if (wallets != null && wallets.length() > 0) {
            val parts = ArrayList<String>()
            for (i in 0 until wallets.length()) {
                val w = wallets.optJSONObject(i) ?: continue
                val currency = w.optString("currency").ifBlank { "CNY" }
                val total = w.optString("total", w.optString("fullBalance"))
                if (total.isNotBlank()) parts.add("$currency $total")
            }
            if (parts.isNotEmpty()) return parts.joinToString(" · ")
        }
        data.optString("total").takeIf { it.isNotBlank() }?.let { return it }
        return data.toString()
    }
}
